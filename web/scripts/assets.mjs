// Copies the shared assets into the web build, so web and Android never diverge:
//   core/design/src/main/res/font/cantarell_*.ttf          → src/generated/fonts/
//   app/src/main/res/drawable/ic_launcher_{background,foreground}.xml → public/icon.svg (+ icon-maskable.svg)
// The day-ring icon is converted from the Android vector drawable: <path> elements become SVG paths.
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "../..");
const web = resolve(here, "..");

const fonts = resolve(web, "src/generated/fonts");
mkdirSync(fonts, { recursive: true });
for (const f of ["cantarell_regular", "cantarell_bold", "cantarell_italic", "cantarell_bolditalic"]) {
  copyFileSync(resolve(root, `core/design/src/main/res/font/${f}.ttf`), resolve(fonts, `${f}.ttf`));
}

/** Android `#AARRGGBB` / `#RRGGBB` → SVG colour + opacity. */
function color(v) {
  if (!v) return null;
  if (v.length === 9) {
    const a = parseInt(v.slice(1, 3), 16) / 255;
    return { c: "#" + v.slice(3), a };
  }
  return { c: v, a: 1 };
}

export function vectorToSvgPaths(xml) {
  const out = [];
  for (const m of xml.matchAll(/<path\b([\s\S]*?)\/>/g)) {
    const attrs = Object.fromEntries([...m[1].matchAll(/android:(\w+)="([^"]*)"/g)].map((a) => [a[1], a[2]]));
    const fill = color(attrs.fillColor);
    const stroke = color(attrs.strokeColor);
    const parts = [`d="${attrs.pathData}"`];
    parts.push(fill && fill.a > 0 ? `fill="${fill.c}"` : `fill="none"`);
    if (stroke && stroke.a > 0) {
      parts.push(`stroke="${stroke.c}"`, `stroke-width="${attrs.strokeWidth ?? 1}"`);
      if (attrs.strokeLineCap) parts.push(`stroke-linecap="${attrs.strokeLineCap}"`);
      if (attrs.strokeLineJoin) parts.push(`stroke-linejoin="${attrs.strokeLineJoin}"`);
    }
    out.push(`<path ${parts.join(" ")}/>`);
  }
  return out;
}

const res = resolve(root, "app/src/main/res/drawable");
const bg = vectorToSvgPaths(readFileSync(resolve(res, "ic_launcher_background.xml"), "utf8"));
const fg = vectorToSvgPaths(readFileSync(resolve(res, "ic_launcher_foreground.xml"), "utf8"));
const header = "<!-- Generated by web/scripts/assets.mjs from app/src/main/res/drawable/ic_launcher_*.xml. -->";
// Maskable: the full 108-unit adaptive canvas (the glyph already sits in the safe zone).
const maskable = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108">${header}${bg.join("")}${fg.join("")}</svg>\n`;
// Regular: the 72-unit visible area, rounded like a launcher icon.
const icon =
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="18 18 72 72">${header}` +
  `<clipPath id="r"><rect x="18" y="18" width="72" height="72" rx="18"/></clipPath>` +
  `<g clip-path="url(#r)">${bg.join("")}${fg.join("")}</g></svg>\n`;
mkdirSync(resolve(web, "public"), { recursive: true });
writeFileSync(resolve(web, "public/icon.svg"), icon);
writeFileSync(resolve(web, "public/icon-maskable.svg"), maskable);
