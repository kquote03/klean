// Generates the web theme from the design tokens (the single source of truth shared with Android):
//   core/design/tokens/klean-color-tokens.json  →  web/src/generated/tokens.css (+ tokens.json copy)
// Light is the default; dark follows the system setting through prefers-color-scheme.
// The variables are M3's --md-sys-color-* names, which @m3e/web components read directly.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const source = resolve(here, "../../core/design/tokens/klean-color-tokens.json");
const outDir = resolve(here, "../src/generated");

export const kebab = (name) => name.replace(/[A-Z]/g, (c) => "-" + c.toLowerCase());

export function cssFor(tokens) {
  const block = (scheme) =>
    Object.entries(tokens[scheme])
      .map(([k, v]) => `  --md-sys-color-${kebab(k)}: ${v.toLowerCase()};`)
      .join("\n");
  return [
    "/* Generated by web/scripts/tokens.mjs from core/design/tokens/klean-color-tokens.json. Do not edit. */",
    ":root {",
    "  color-scheme: light dark;",
    block("light"),
    "}",
    "@media (prefers-color-scheme: dark) {",
    "  :root {",
    block("dark").replace(/^/gm, "  "),
    "  }",
    "}",
    "",
  ].join("\n");
}

const isMain = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const tokens = JSON.parse(readFileSync(source, "utf8"));
  mkdirSync(outDir, { recursive: true });
  writeFileSync(resolve(outDir, "tokens.css"), cssFor(tokens));
  writeFileSync(resolve(outDir, "tokens.json"), JSON.stringify(tokens, null, 2) + "\n");
}
